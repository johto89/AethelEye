{
    None,
    Contains,
    Regex,
    EnvFile,
    SqlDump,
}

public sealed record HiddenPath(
    string Path,
    Severity Severity,
    HiddenPathValidation Validation,
    string? Marker,
    string Description,
    bool AllowHtml = false);

