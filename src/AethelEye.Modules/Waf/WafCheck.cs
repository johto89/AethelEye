    public string Id => "waf";

    public string Name => "WAF fingerprint";

    public string Description =>
        "Detects common WAF/CDN signatures from headers, cookies and one safe probe (wafw00f-inspired).";

    public int Order => 15;

    public async Task<CheckResult> RunAsync(ICheckContext context)
    {
        var result = new CheckResult { CheckId = Id, CheckName = Name };
        var page = await context.Pages.GetAsync(context.Target.BaseUri, context.CancellationToken);

        var detections = new Dictionary<string, Detection>(StringComparer.OrdinalIgnoreCase);
        Evaluate(page, detections);

        var activeProbe = context.Settings.GetBool("activeProbe", true);
        HttpResponseData? probe = null;
        if (activeProbe)
        {
            try
            {
                var payload = context.Settings.GetString("probePayload")
                    ?? "<script>alert(1)</script>";
                var builder = new UriBuilder(context.Target.BaseUri);
                var existing = builder.Query.TrimStart('?');
                var probeQuery = "aetheleye_waf_probe=" + Uri.EscapeDataString(payload);
                builder.Query = existing.Length > 0 ? existing + "&" + probeQuery : probeQuery;
                probe = await context.Http.GetAsync(builder.Uri, context.CancellationToken);
                Evaluate(probe, detections);

                if (probe.StatusCode is 403 or 406 or 429 or 503
                    && page.StatusCode < 400
                    && BodyContains(probe,
                        "blocked", "denied", "forbidden", "security", "firewall",
                        "captcha", "challenge", "not acceptable"))
                {
                    Add(detections, new Detection(
                        "Generic WAF/IPS block",
                        Confidence.Low,
                        [$"HTTP {probe.StatusCode} after probe"]));
                }
            }
            catch (Exception error) when (error is not OperationCanceledException)
            {
                result.Notes.Add("Active WAF probe failed: " + error.Message);
            }
        }

        result.Metrics["activeProbe"] = activeProbe ? "true" : "false";
        result.Metrics["baselineStatus"] = page.StatusCode.ToString();
        if (probe is not null)
        {
            result.Metrics["probeStatus"] = probe.StatusCode.ToString();
        }

        if (detections.Count == 0)
        {
            result.Status = CheckStatus.NoRisk;
            result.Summary = "No WAF/CDN fingerprint observed from headers, cookies or the probe.";
            result.Notes.Add(
                "Absence of a signature does not prove that no WAF exists; " +
                "some deployments hide all identifying headers.");
            return result;
        }

        var ordered = detections.Values
            .OrderByDescending(detection => detection.Confidence)
            .ThenBy(detection => detection.Vendor, StringComparer.OrdinalIgnoreCase)
            .ToList();
        var highest = ordered.Max(detection => detection.Confidence);
        var matched = ordered
            .SelectMany(detection => detection.Evidence.Select(evidence => $"{detection.Vendor}: {evidence}"))
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .ToList();

        result.Findings.Add(new Finding
        {
            CheckId = Id,
            Title = "Web application firewall detected: " +
                    string.Join(", ", ordered.Select(detection => detection.Vendor)),
            Description =
                "Signatures associated with a WAF/CDN were observed. This is inventory information: " +
                "a WAF does not mean the application is secure, and it may mask some findings.",
            Severity = Severity.Info,
            Confidence = highest,
            Target = context.Target.BaseUrl,
            Url = page.FinalUri.ToString(),
            Evidence = new Dictionary<string, string>
            {
                ["vendors"] = string.Join(", ", ordered.Select(detection => detection.Vendor)),
                ["matched"] = string.Join("; ", matched),
                ["baselineStatus"] = page.StatusCode.ToString(),
                ["probeStatus"] = probe?.StatusCode.ToString() ?? string.Empty,
                ["server"] = page.Header("Server") ?? string.Empty,
            },
            References = ["https://github.com/EnableSecurity/wafw00f"],
        });

        result.Status = CheckStatus.NoRisk;
        result.Summary = $"Detected {ordered.Count} WAF/CDN signature(s).";
        result.Metrics["vendors"] = ordered.Count.ToString();
        return result;
    }

    private static void Evaluate(
        HttpResponseData response,
        Dictionary<string, Detection> detections)
    {
        foreach (var rule in Rules)
        {
            var evidence = rule.Match(response);
            if (evidence is not null)
            {
                Add(detections, new Detection(rule.Vendor, rule.Confidence, [evidence]));
            }
        }
    }

    private static void Add(Dictionary<string, Detection> detections, Detection detection)
    {
        if (detections.TryGetValue(detection.Vendor, out var existing))
        {
            existing.Evidence.AddRange(detection.Evidence);
            if (detection.Confidence > existing.Confidence)
            {
                detections[detection.Vendor] = existing with { Confidence = detection.Confidence };
            }

            return;
        }

        detections[detection.Vendor] = detection;
    }

    private static bool HeaderPresent(HttpResponseData response, string name) =>
        response.Headers.ContainsKey(name);

    private static bool HeaderContains(HttpResponseData response, string name, string value) =>
        response.Headers.TryGetValue(name, out var values)
        && values.Any(item => item.Contains(value, StringComparison.OrdinalIgnoreCase));

    private static bool Cookie(HttpResponseData response, string name) =>
        response.Header("Set-Cookie")?.Contains(name, StringComparison.OrdinalIgnoreCase) == true;

    private static bool BodyContains(HttpResponseData response, params string[] markers) =>
        markers.Any(marker => response.Text.Contains(marker, StringComparison.OrdinalIgnoreCase));
}
