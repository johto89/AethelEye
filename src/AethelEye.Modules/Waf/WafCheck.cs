using AethelEye.Core.Abstractions;
using AethelEye.Core.Http;
using AethelEye.Core.Models;

namespace AethelEye.Modules.Waf;

/// <summary>
/// Passive plus one safe active probe for common WAF/CDN signatures. A WAF is inventory
/// information, not a vulnerability, so the finding severity is always Info.
/// </summary>
public sealed class WafCheck : ICheck
{
    private sealed record Detection(
        string Vendor,
        Confidence Confidence,
        List<string> Evidence);

    private sealed record Rule(
        string Vendor,
        Confidence Confidence,
        Func<HttpResponseData, string?> Match);

    private static readonly Rule[] Rules =
    [
        new("Cloudflare", Confidence.High, response =>
            HeaderContains(response, "server", "cloudflare") ? "Server: cloudflare"
            : HeaderPresent(response, "cf-ray") ? "CF-Ray header"
            : Cookie(response, "__cfduid") || Cookie(response, "cf_clearance") ? "Cloudflare cookie"
            : BodyContains(response, "Attention Required! | Cloudflare", "cf-error-details", "Cloudflare Ray ID")
                ? "Cloudflare block page"
            : null),

        new("Akamai", Confidence.High, response =>
            HeaderContains(response, "server", "AkamaiGHost") ? "Server: AkamaiGHost"
            : HeaderContains(response, "x-akamai", "") ? "X-Akamai header"
            : Cookie(response, "ak_bmsc") || Cookie(response, "bm_sz") || Cookie(response, "_abck")
                ? "Akamai bot cookie"
            : BodyContains(response, "Access Denied Reference")
                ? "Akamai block page"
            : null),

        new("Imperva / Incapsula", Confidence.High, response =>
            HeaderPresent(response, "x-iinfo") ? "X-Iinfo header"
            : Cookie(response, "incap_ses_") || Cookie(response, "visid_incap_")
                ? "Incapsula cookie"
            : BodyContains(response, "Incapsula incident ID", "Request unsuccessful. Incapsula")
                ? "Incapsula block page"
            : null),

        new("AWS WAF / CloudFront", Confidence.Medium, response =>
            HeaderPresent(response, "x-amz-cf-id") || HeaderPresent(response, "x-amz-cf-pop")
                ? "CloudFront header"
            : HeaderContains(response, "server", "CloudFront") ? "Server: CloudFront"
            : HeaderPresent(response, "x-amzn-waf-action") ? "AWS WAF action header"
            : BodyContains(response, "Request blocked", "AWS WAF")
                ? "AWS WAF block page"
            : null),

        new("Sucuri", Confidence.High, response =>
            HeaderPresent(response, "x-sucuri-id") || HeaderPresent(response, "x-sucuri-cache")
                ? "X-Sucuri header"
            : HeaderContains(response, "server", "Sucuri") ? "Server: Sucuri"
            : BodyContains(response, "Sucuri WebSite Firewall", "Access Denied - Sucuri")
                ? "Sucuri block page"
            : null),

        new("F5 BIG-IP", Confidence.Medium, response =>
            Cookie(response, "BIGipServer") || Cookie(response, "TS01")
                ? "BIG-IP cookie"
            : HeaderPresent(response, "x-wa-info") ? "X-WA-Info header"
            : HeaderContains(response, "server", "BIG-IP") ? "Server: BIG-IP"
            : BodyContains(response, "The requested URL was rejected")
                ? "BIG-IP block page"
            : null),

        new("FortiWeb", Confidence.High, response =>
            Cookie(response, "FORTIWAFSID") ? "FORTIWAFSID cookie"
            : HeaderPresent(response, "x-fortiweb") ? "X-FortiWeb header"
            : BodyContains(response, "FortiWeb") ? "FortiWeb block page"
            : null),

        new("Barracuda", Confidence.Medium, response =>
            Cookie(response, "barra_counter_session") || Cookie(response, "barra_session")
                ? "Barracuda cookie"
            : BodyContains(response, "Barracuda", "barra_counter_session")
                ? "Barracuda block page"
            : null),

        new("ModSecurity", Confidence.Medium, response =>
            HeaderContains(response, "server", "ModSecurity") ? "Server: ModSecurity"
            : HeaderPresent(response, "x-mod-security") ? "X-Mod-Security header"
            : BodyContains(response, "ModSecurity", "Not Acceptable!")
                ? "ModSecurity block page"
            : null),

        new("Wordfence", Confidence.Medium, response =>
            Cookie(response, "wordfence_verifiedHuman") ? "Wordfence cookie"
