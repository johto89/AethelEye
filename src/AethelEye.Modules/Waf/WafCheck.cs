                ? "Wordfence block page"
            : null),

        new("Fastly", Confidence.Medium, response =>
            HeaderPresent(response, "x-fastly-request-id") ? "X-Fastly-Request-ID header"
            : HeaderContains(response, "x-served-by", "fastly") ? "X-Served-By: fastly"
